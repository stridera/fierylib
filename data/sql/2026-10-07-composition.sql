EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

ALTER TABLE "Mobs" ADD COLUMN IF NOT EXISTS "composition" "Composition" NOT NULL DEFAULT 'FLESH';
ALTER TABLE "Races" ADD COLUMN IF NOT EXISTS "default_composition" "Composition" NOT NULL DEFAULT 'FLESH';

UPDATE "Races" SET "default_composition" = v.comp::"Composition"
FROM (VALUES
    ('PLANT', 'PLANT'),
    ('ARBOREAN', 'PLANT')
) AS v(race, comp)
WHERE "Races"."race" = v.race::"Race" AND "Races"."default_composition" = 'FLESH';

