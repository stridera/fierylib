-- Composition: what a creature is physically made of (flesh, stone, plant, ...).
--
-- Mirrors `prisma db push` for the new enum + columns, then backfills non-FLESH
-- values from the legacy data so prod does not need a reimport:
--   * "Mobs".composition          <- `Composition:` in lib/world/mob/*.mob (253 mobs, AIR=23, BONE=25, EARTH=8, ETHER=64, FIRE=11, ICE=9, LAVA=2, METAL=7, MIST=17, PLANT=44, STONE=30, WATER=13)
--   * "Races".default_composition <- races.cpp def_composition (2 races: PLANT=PLANT, ARBOREAN=PLANT)
-- FLESH is the column default, so only non-FLESH rows are listed.
--
-- Idempotent: type creation is guarded, columns use IF NOT EXISTS, and the UPDATEs only
-- touch rows still at FLESH (never overwrite a builder's edit; re-run is a no-op).
-- Mobs missing from "Mobs" are skipped by the join.
-- Generated by scripts/gen_composition_sql.py (id = mob vnum - zone*100).

