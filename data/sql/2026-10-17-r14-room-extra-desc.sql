-- fierymud-rs playtest r14 B4: room extra descriptions lost their line breaks on import.
--
-- World.parse folded every `~` string onto one line, so the Academy directory sign (519:2, 519:8)
-- and the other multi-line extra descriptions of the zones below were imported as one long line.
-- The parser now keeps the layout (MudData.read_text); this patch repairs rows imported before that.
--
-- Zones: 519. 15 extra descriptions.
--
-- Guarded: a row is rewritten only while it holds the folded text (no line break, equal to the new
-- text once whitespace is collapsed), so anything edited in Muditor since is left alone. Idempotent:
-- after a run the row holds the new text, so a rerun matches nothing.
-- Generated by scripts/gen_room_extra_desc_newlines_sql.py from lib/world/wld/*.wld.

BEGIN;

UPDATE "RoomExtraDescriptions" AS d
SET description = v.txt
FROM (VALUES
  (519, 0, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 1, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 1, ARRAY['purple', 'curtain']::text[], $d$The heavy purple velvet curtain is embroidered with the Ethilien Training
Academy crest.  It seems to hide a door of some kind.$d$),
  (519, 1, ARRAY['tables', 'chairs']::text[], $d$The furniture in the room is old and worn from centuries of use.  Impressions
from thousands of notes mark the tables' surfaces.$d$),
  (519, 2, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 2, ARRAY['large-directory-sign']::text[], $d$North - Academy Arena
East - The Chapel
South - Laboratory of Applied Arcanics
Down - Stealth Studies Classroom$d$),
  (519, 3, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 4, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 5, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 6, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 8, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 8, ARRAY['large-directory-sign']::text[], $d$North - Academy Arena
East - The Chapel
South - Laboratory of Applied Arcanics
Down - Stealth Studies Classroom$d$),
  (519, 9, ARRAY['academy-crest']::text[], $d$The Ethilien Training Academy crest is a dragon curled around a tree, its mouth
open in a roar.$d$),
  (519, 9, ARRAY['purple', 'curtain']::text[], $d$The heavy purple velvet curtain is embroidered with the Ethilien Training
Academy crest.  It seems to hide a door of some kind.$d$),
  (519, 9, ARRAY['tables', 'chairs']::text[], $d$The furniture in the room is old and worn from centuries of use.  Impressions
from thousands of notes mark the tables' surfaces.$d$)
) AS v(zone_id, room_id, kw, txt)
WHERE d.room_zone_id = v.zone_id AND d.room_id = v.room_id
  AND d.keywords = v.kw
  AND position(E'\n' in d.description) = 0
  AND btrim(regexp_replace(d.description, '\s+', ' ', 'g')) = btrim(regexp_replace(v.txt, '\s+', ' ', 'g'));

COMMIT;
