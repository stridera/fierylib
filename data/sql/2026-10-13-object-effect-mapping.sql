-- fierymud-rs #151: object effect bits were imported through the wrong word shifts.
--
-- Object.parse rebuilt the legacy EFF_* bitvector as eff3 << 26 | eff2 << 13 | eff1; the legacy
-- words are 32 bits wide (eff3 << 64 | eff2 << 32 | eff1). Objects with a non-zero second / third
-- word got the wrong effects: the "dagger of ice" (EFF_ICE_WEAPON, bit 85) became MAJOR_GLOBE
-- (bit 47) and lost its ice attribute, ~130 other objects got wrong globes, status flags and
-- resistances (the 2026-10-08 object-flag-effects backfills were generated from the same parser).
--
-- 1. 132 objects: the worn `status` flags, `globe` row and ObjectResistance rows are rewritten to what
--    the fixed importer produces. GUARD: only objects whose CURRENT status flags, globe circle and
--    resistances equal the buggy import's output exactly (and whose status row carries nothing but
--    "flags") are touched, so anything edited in Muditor since is left alone.
-- 2. Elemental weapons get Objects.weapon_element (new nullable "DamageType" column, added here if
--    missing; DDL identical to what `prisma db push` creates from the muditor schema). 29 weapons carry
--    EFF_FIRE/ICE/POISON/SHOCK/ACID/RADIANT_WEAPON: they deal that element (legacy convert_weapon_damage)
--    but KEEP their physical weapon_damage_type, which drives the weapon family / proficiency and mob AI
--    weapon requirements (legacy weapon_proficiency reads the raw type). Weapons whose raw legacy type is
--    itself an element (phase staffs / wands, zone 2) get weapon_element = that element; legacy gives them
--    no weapon family (weapon_proficiency returns -1), so their damage type is left as is.
-- Idempotent: after a run the current state equals the new state, never the old one, so a second run
-- changes 0 rows. Keyed by (zone_id, id) only. Deploy order: muditor schema push (or this file's
-- ALTER) before the fierymud-rs build that reads the column.
-- Generated by scripts/gen_object_effect_mapping_sql.py from lib/world/obj/*.obj.

