UPDATE "Objects" o
   SET values = jsonb_set(o.values, '{Key}', jsonb_build_object('zone', m.zone, 'id', m.id))
  FROM _container_key_map m
 WHERE o.type = 'CONTAINER'
   AND jsonb_typeof(o.values->'Key') = 'number'
   AND (o.values->>'Key')::int = m.legacy;

UPDATE "CharacterItems" c
   SET custom_values = jsonb_set(c.custom_values, '{Key}', jsonb_build_object('zone', m.zone, 'id', m.id))
  FROM _container_key_map m
 WHERE jsonb_typeof(c.custom_values->'Key') = 'number'
   AND (c.custom_values->>'Key')::int = m.legacy;

COMMIT;
