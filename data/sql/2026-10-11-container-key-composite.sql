-- CONTAINER keys as composite ids. "Objects".values->'Key' held the legacy vnum (e.g. 2302 on 23:1);
-- it is now {"zone": 23, "id": 2} (fierylib object_importer.composite_container_key, resolved through
-- the zone ranges in lib/world/zon: zone 30 spans 3000-3499, so 3123 is 30:123, not 31:23).
-- Also rewrites the saved per-instance copies in "CharacterItems".custom_values, which the runtime
-- overlays on the prototype. Keys <= 0 ("no key") are left alone.
--
-- Three keys point at objects that do not exist in the legacy data (51 -> 0:51, 1680 -> 16:80,
-- 7911 -> 79:11, no zone range, vnum//100 fallback). They keep the same dangling reference as before.
--
-- Idempotent: only rows whose Key is still a positive JSON number are touched, and each becomes an
-- object, so a second run changes 0 rows.
-- Generated by scripts/gen_container_key_sql.py (34 legacy keys).

BEGIN;

CREATE TEMP TABLE _container_key_map (legacy integer PRIMARY KEY, zone integer NOT NULL, id integer NOT NULL) ON COMMIT DROP;
INSERT INTO _container_key_map (legacy, zone, id) VALUES
