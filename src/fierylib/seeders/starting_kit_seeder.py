"""Starting kit seeder (what a new character is handed in their pack).

Legacy handed it out in ``give_newbie_eq()`` (class.cpp): ``common_newbie_eq[]``
for every class plus the class's own ``newbie_eq[]``, to a character created at
level 4 or below. It gave no coin. The game now reads the ``StartingKit`` table,
seeded here from ``data/starting_kit.json``::

    {"class": null, "object": {"zone": 0, "id": 23}, "quantity": 1}
    {"class": "Warrior", "object": {"zone": 10, "id": 14}, "quantity": 1}

``class`` is ``Class.plain_name`` (null = every class), so the rows survive an id
renumbering. Rows are only ever added: an existing (class, object) row is left
alone so builder edits survive a re-seed. Row order is the order the items are
handed out.

Run after the classes and the world objects are seeded. An idempotent SQL
equivalent for already-seeded databases is generated by :func:`build_sql` into
``data/sql/2026-10-12-starting-kit.sql``.
"""

import json
from pathlib import Path

from prisma import Prisma

KIT_JSON = Path(__file__).resolve().parents[3] / "data" / "starting_kit.json"

_COLUMNS = "class_id, object_zone_id, object_id, quantity"


def load_items() -> list[dict]:
    """The kit entries from ``data/starting_kit.json``, in insert order."""
    with open(KIT_JSON, encoding="utf-8") as f:
        return json.load(f)["items"]


def _lit(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _values_row(ord_: int, r: dict) -> str:
    cls = _lit(r["class"]) if r.get("class") is not None else "NULL::text"
    obj = r["object"]
    return f"    ({ord_}, {cls}, {obj['zone']}, {obj['id']}, {r.get('quantity', 1)})"


def build_sql(items: list[dict] | None = None) -> str:
    """Idempotent SQL patch equivalent to :meth:`StartingKitSeeder.seed_starting_kit`."""
    items = load_items() if items is None else items
    rows = ",\n".join(_values_row(i, r) for i, r in enumerate(items, start=1))
    return f'''-- StartingKit: what a new character is handed in their pack, moved out of
-- legacy give_newbie_eq() (class.cpp) into data (data over code).
--
--   class_id NULL   every class (legacy common_newbie_eq[]: small leather bag,
--                   iron rations, water skin, wooden torch, small map of
--                   Mielikki, quest journal)
--   class_id set    that class only (legacy classes[].newbie_eq[]: the crude
--                   weapon and light armour, or the sorcerer's spellbook, quill,
--                   linen leggings, hood, sandals and dagger)
--
-- Legacy gave no coin, so there is no coin column. Rows are handed out in `id`
-- order. Keyed by Class.plain_name, so ids may differ per database. No FK on the
-- object: a partial world import must not block the seed, and the game logs a
-- missing proto.
--
-- Idempotent and builder-safe: the table is created IF NOT EXISTS and a row is
-- inserted only when no row exists for its (class, object). A second run
-- changes nothing. Keep in sync with the Prisma model StartingKit in
-- muditor/packages/db/prisma/schema.prisma. Generated from
-- data/starting_kit.json; a unit test keeps the two in sync.

BEGIN;

CREATE TABLE IF NOT EXISTS "StartingKit" (
    "id" SERIAL NOT NULL,
    "class_id" INTEGER,
    "object_zone_id" INTEGER NOT NULL,
    "object_id" INTEGER NOT NULL,
    "quantity" INTEGER NOT NULL DEFAULT 1,

    CONSTRAINT "StartingKit_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "StartingKit_class_id_fkey" FOREIGN KEY ("class_id") REFERENCES "Class"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "StartingKit_class_id_object_zone_id_object_id_key"
    ON "StartingKit"("class_id", "object_zone_id", "object_id");

INSERT INTO "StartingKit" ({_COLUMNS})
SELECT c.id, v.zone, v.obj, v.qty
FROM (VALUES
{rows}
) AS v(ord, class_name, zone, obj, qty)
LEFT JOIN "Class" c ON c.plain_name = v.class_name
WHERE (v.class_name IS NULL OR c.id IS NOT NULL)
  AND NOT EXISTS (
      SELECT 1 FROM "StartingKit" k
      WHERE k.class_id IS NOT DISTINCT FROM c.id
        AND k.object_zone_id = v.zone
        AND k.object_id = v.obj
  )
ORDER BY v.ord;

COMMIT;
'''


# One kit row per statement; $1 class plain_name, $2 object zone, $3 object id,
# $4 quantity.
_INSERT_ROW = f"""
INSERT INTO "StartingKit" ({_COLUMNS})
SELECT c.id, $2::int, $3::int, $4::int
FROM (SELECT 1) AS one
LEFT JOIN "Class" c ON c.plain_name = $1::text
WHERE ($1::text IS NULL OR c.id IS NOT NULL)
  AND NOT EXISTS (
      SELECT 1 FROM "StartingKit" k
      WHERE k.class_id IS NOT DISTINCT FROM c.id
        AND k.object_zone_id = $2::int
        AND k.object_id = $3::int
  )
"""


class StartingKitSeeder:
    """Inserts the ``StartingKit`` rows; existing rows are left untouched."""

    def __init__(self, prisma: Prisma):
        self.prisma = prisma

    async def seed_starting_kit(self, verbose: bool = False) -> dict:
        """Add every missing kit row. Returns counts."""
        stats = {"inserted": 0, "existing": 0, "total": 0}
        for r in load_items():
            stats["total"] += 1
            obj = r["object"]
            n = await self.prisma.execute_raw(
                _INSERT_ROW,
                r.get("class"),
                obj["zone"],
                obj["id"],
                r.get("quantity", 1),
            )
            if n:
                stats["inserted"] += 1
            else:
                stats["existing"] += 1
            if verbose:
                label = r.get("class") or "all classes"
                print(f"  {label} {obj['zone']}:{obj['id']}: {'added' if n else 'kept'}")
        return stats
