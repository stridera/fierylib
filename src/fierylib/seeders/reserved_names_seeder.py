"""Reserved names seeder: words refused as character names, moved out of the Rust server.

The game loads the ``"ReservedNames"`` table at boot (data over code); builders edit it in
Muditor (/dashboard/admin/reserved-names). Source of truth for the seed rows is
``data/reserved_names.json``::

    reserved_names  [name, reason]  -> "ReservedNames" (lowercase names)

The command-grammar words (all / self / me / everyone / someone / something / here) are not
rows: they belong to the command parser and stay in the game's code.

Rows are only ever added: an existing row is left alone so builder edits and removals of
other rows survive a re-seed. An idempotent SQL equivalent for already-seeded databases is
generated by :func:`build_sql` into ``data/sql/2026-10-10-reserved-names.sql`` (a unit test
keeps the two in sync). The table shape mirrors ``model ReservedNames`` in
muditor/packages/db/prisma/schema.prisma.
"""

import json
from pathlib import Path

from prisma import Prisma

RESERVED_JSON = Path(__file__).resolve().parents[3] / "data" / "reserved_names.json"

DDL = [
    """CREATE TABLE IF NOT EXISTS "ReservedNames" (
    "id" SERIAL NOT NULL,
    "name" TEXT NOT NULL,
    "reason" TEXT,
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ReservedNames_pkey" PRIMARY KEY ("id")
)""",
    'CREATE UNIQUE INDEX IF NOT EXISTS "ReservedNames_name_key" ON "ReservedNames"("name")',
]


def load_reserved_names() -> list[list[str]]:
    """The ``[name, reason]`` pairs of ``data/reserved_names.json``."""
    with open(RESERVED_JSON, encoding="utf-8") as f:
        return json.load(f)["reserved_names"]


def _lit(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_statements(rows: list[list[str]] | None = None) -> list[str]:
    """Every statement of the patch, in order, without BEGIN/COMMIT or trailing semicolons."""
    pairs = load_reserved_names() if rows is None else rows
    values = ",\n".join(f"  ({_lit(n)}, {_lit(r)})" for n, r in pairs)
    return [
        *DDL,
        'INSERT INTO "ReservedNames" ("name", "reason") VALUES\n' + values + '\nON CONFLICT ("name") DO NOTHING',
    ]


def build_sql(rows: list[list[str]] | None = None) -> str:
    """The idempotent SQL patch, equivalent to :meth:`ReservedNamesSeeder.seed_reserved_names`."""
    body = ";\n\n".join(build_statements(rows))
    return f"""-- ReservedNames: words refused as character names (staff/system voices and generic mob
-- words), moved out of the game server's source (data over code). Builders edit the table in
-- Muditor; the game loads it at boot and logs an ERROR and falls back to an empty list when
-- the table is missing, so applying this by hand after the deploy is safe.
--
-- The command-grammar words (all/self/me/everyone/someone/something/here) are not rows: they
-- stay in the game's code. Names are stored lowercase; the game compares case-insensitively.
--
-- Idempotent and builder-safe: the table is created IF NOT EXISTS and rows are inserted only
-- when missing (ON CONFLICT DO NOTHING). Keep in sync with model ReservedNames in
-- muditor/packages/db/prisma/schema.prisma (and muditor/deploy/prod/sql/070-reserved-names.sql).
-- Generated from data/reserved_names.json; a unit test keeps the two in sync.

BEGIN;

{body};

COMMIT;
"""


class ReservedNamesSeeder:
    """Adds the missing reserved-name rows; existing rows are left untouched."""

    def __init__(self, prisma: Prisma):
        self.prisma = prisma

    async def seed_reserved_names(self, verbose: bool = False) -> dict:
        """Run every statement of the patch. Returns rows touched per statement."""
        stats = {"statements": 0, "rows": 0}
        for stmt in build_statements():
            n = await self.prisma.execute_raw(stmt)
            stats["statements"] += 1
            stats["rows"] += n or 0
            if verbose:
                print(f"  {stmt.splitlines()[0][:70]}: {n}")
        return stats
