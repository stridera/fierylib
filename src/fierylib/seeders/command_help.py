"""Command help text: the "Command".help_summary / help_text seed.

Shared by scripts/gen_command_help_sql.py (writes
data/sql/2026-10-12-command-help-text.sql) and CommandSeeder (runs the same
statements after a reset).

Source: data/command_help.json, a dump of the fierymud-rs command REGISTRY (name, aliases,
category label, min_role, usage, summary, long). Commands the table lacks are inserted;
existing rows only get help_summary / help_text filled while NULL or empty, so Muditor
edits survive.
"""

import json
from pathlib import Path

DATA_PATH = Path(__file__).resolve().parents[3] / "data" / "command_help.json"

# fierymud-rs Category label -> CommandCategory enum value.
CATEGORY = {
    "Information": "INFORMATION",
    "Movement": "MOVEMENT",
    "Communication": "COMMUNICATION",
    "Combat": "COMBAT",
    "Magic": "MAGIC",
    "Inventory": "OBJECT",
    "Group": "SYSTEM",
    "Mount": "MOVEMENT",
    "Banking": "OBJECT",
    "Quest": "SYSTEM",
    "Mail": "COMMUNICATION",
    "Settings": "SYSTEM",
    "Admin": "ADMIN",
}

TAG = "$cmdhelp$"

# Same DDL as Prisma `db push`; lets the patch run before the schema push.
COLUMN_DDL = [
    'ALTER TABLE "Command" ADD COLUMN IF NOT EXISTS "help_summary" TEXT',
    'ALTER TABLE "Command" ADD COLUMN IF NOT EXISTS "help_text" TEXT',
]


def load_rows(path: Path = DATA_PATH) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))


def q(value: str | None) -> str:
    """Dollar-quoted literal (exact: newlines, quotes, backslashes); NULL when empty."""
    if value is None or value == "":
        return "NULL"
    assert TAG not in value, value
    return f"{TAG}{value}{TAG}"


def _aliases(values: list[str]) -> str:
    if not values:
        return "ARRAY[]::text[]"
    return "ARRAY[" + ", ".join(q(v) for v in values) + "]::text[]"


def insert_sql(rows: list[dict]) -> str:
    """One INSERT ... ON CONFLICT statement covering every row (no trailing semicolon)."""
    values = []
    for r in sorted(rows, key=lambda r: r["name"]):
        values.append(
            "    ("
            + ", ".join(
                [
                    q(r["name"]),
                    _aliases(r["aliases"]),
                    f"'{CATEGORY[r['category']]}'::\"CommandCategory\"",
                    q(r["summary"]),
                    q(r["usage"]),
                    "false" if r["min_role"] == "Player" else "true",
                    q(r["summary"]),
                    q(r["long"]),
                ]
            )
            + ")"
        )
    return (
        'INSERT INTO "Command" ("name", "aliases", "category", "description", "usage",\n'
        '    "immortal_only", "help_summary", "help_text", "updated_at")\n'
        "SELECT v.name, v.aliases, v.category, v.description, v.usage, v.immortal_only,\n"
        "    v.help_summary, v.help_text, now()\n"
        "FROM (VALUES\n"
        + ",\n".join(values)
        + "\n) AS v(name, aliases, category, description, usage, immortal_only,"
        " help_summary, help_text)\n"
        'ON CONFLICT ("name") DO UPDATE SET\n'
        '    "help_summary" = CASE WHEN COALESCE("Command"."help_summary", \'\') = \'\'\n'
        '        THEN EXCLUDED."help_summary" ELSE "Command"."help_summary" END,\n'
        '    "help_text" = CASE WHEN COALESCE("Command"."help_text", \'\') = \'\'\n'
        '        THEN EXCLUDED."help_text" ELSE "Command"."help_text" END'
    )


HEADER = """-- Command help text (data-over-code).
--
-- `help <command>` in fierymud-rs shows a one-line summary and a long paragraph that used to
-- exist only as Rust strings. They now live in "Command".help_summary / help_text, editable in
-- Muditor. Command.description / usage are an older, differently worded catalog and are not
-- touched. The game uses, in order: a matching HelpEntry, the Command row's text, then the
-- built-in Rust string (so output is identical with or without this patch).
--
-- This patch:
--   * adds the two columns if missing (same DDL as Prisma `db push`);
--   * inserts a "Command" row for each game command the table lacks (category and
--     immortal_only derived from the registry; description / usage = its summary / usage);
--   * fills help_summary / help_text only while NULL or empty, so Muditor edits win.
--
-- {n_rows} commands. Generated by scripts/gen_command_help_sql.py from
-- data/command_help.json. Idempotent: rerunning changes nothing.

BEGIN;

"""


def patch_sql(rows: list[dict]) -> str:
    ddl = "".join(f"{s};\n" for s in COLUMN_DDL)
    return HEADER.format(n_rows=len(rows)) + ddl + "\n" + insert_sql(rows) + ";\n\nCOMMIT;\n"
