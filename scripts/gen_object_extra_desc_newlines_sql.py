#!/usr/bin/env python3
"""Generate the object extra-description line-break repair (data/sql/2026-10-13-object-extra-desc-newlines.sql).

fierymud-rs playtest r10 #33: `read map` printed the Academy map as one 2,173-character line.

Root cause: MudData.read_string folded every `~` string onto one line (stripping indentation and
dropping blank lines) and split_by_delimiter had already stripped the lines it handed out. Object
extra descriptions (maps, signs, scrolls, ASCII art) lost their layout on import. The parser now
reads them with MudData.read_text, which keeps line breaks and indentation.

This script re-reads lib/world/obj/*.obj with the fixed parser and emits a guarded, idempotent SQL
patch for every object whose imported text should have had line breaks: Objects.examine_description
(the extra description matching the object's own keywords, chosen exactly as the importer does) and
the remaining ObjectExtraDescriptions rows. A row is rewritten only while it still holds the folded
single-line text (no line break, and equal to the new text once whitespace is collapsed), so text
edited in Muditor since the import is left alone.

Usage:
    python scripts/gen_object_extra_desc_newlines_sql.py --lib /path/to/lib [--out PATH]
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from mud.mudfile import MudData  # noqa: E402
from mud.types.object import Object  # noqa: E402

from fierylib.converters import convert_legacy_colors, strip_articles, strip_markup  # noqa: E402
from fierylib.importers.object_importer import ObjectImporter  # noqa: E402

DEFAULT_OUT = (
    Path(__file__).resolve().parent.parent / "data" / "sql" / "2026-10-13-object-extra-desc-newlines.sql"
)
TAG = "$d$"


def lit(text: str) -> str:
    assert TAG not in text, "text contains the dollar-quote tag"
    return f"{TAG}{text}{TAG}"


def collect(lib: Path):
    examine_rows, extra_rows, failed = [], [], []
    for f in sorted((p for p in lib.glob("world/obj/*.obj") if p.stem.isdigit()), key=lambda p: int(p.stem)):
        zone = int(f.stem)
        try:
            objs = Object.parse(MudData(f.read_text(encoding="latin-1").split("\n")))
        except Exception as e:
            failed.append((f.name, str(e)))
            continue
        for obj in objs:
            oid = obj.id - zone * 100
            obj_kw = [k.lower() for k in (obj.keywords or [])]
            matching, others = [], []
            for extra in obj.extras or []:
                if any(k.lower() in obj_kw for k in extra.keywords or []):
                    matching.append(extra)
                else:
                    others.append(extra)
            selected = None
            preferred = ObjectImporter.EXTRA_DESCRIPTION_OVERRIDES.get((zone, oid))
            if preferred:
                for extra in matching:
                    kws = [k.lower() for k in extra.keywords]
                    if all(p.lower() in kws for p in preferred):
                        selected = extra
                        break
            if selected is None and matching:
                selected = matching[0]
            if selected is not None and "\n" in selected.text:
                text = convert_legacy_colors(selected.text)
                examine_rows.append((zone, oid, text, strip_markup(text)))
            for extra in others:
                if "\n" in extra.text:
                    kws = strip_articles(extra.keywords)
                    extra_rows.append((zone, oid, kws, convert_legacy_colors(extra.text)))
    return examine_rows, extra_rows, failed


COLLAPSE = "btrim(regexp_replace({col}, '\\s+', ' ', 'g'))"

HEADER = """-- fierymud-rs playtest r10 #33: object extra descriptions lost their line breaks on import.
--
-- MudData.read_string folded every `~` string onto one line, so the Academy map (and every other map,
-- sign and ASCII-art scroll) was imported as a single 2,000+ character line. The importer now keeps
-- the layout (MudData.read_text); this patch repairs rows imported before that.
--
-- {n_examine} objects: Objects.examine_description / plain_examine_description (the extra description
-- matching the object's own keywords, which `look` / `read` show).
-- {n_extra} extra descriptions: ObjectExtraDescriptions.description (other keywords).
--
-- Guarded: a row is rewritten only while it holds the folded text (no line break, equal to the new
-- text once whitespace is collapsed), so anything edited in Muditor since is left alone. Idempotent:
-- after a run the row holds the new text, so a rerun matches nothing.
-- Generated by scripts/gen_object_extra_desc_newlines_sql.py from lib/world/obj/*.obj.

BEGIN;
"""

EXAMINE_SQL = """
UPDATE "Objects" AS o
SET examine_description = v.txt,
    plain_examine_description = v.plain,
    updated_at = now()
FROM (VALUES
{rows}
) AS v(zone_id, id, txt, plain)
WHERE o.zone_id = v.zone_id AND o.id = v.id
  AND o.examine_description IS NOT NULL
  AND position(E'\\n' in o.examine_description) = 0
  AND {old} = {new};
"""

EXTRA_SQL = """
UPDATE "ObjectExtraDescriptions" AS d
SET description = v.txt
FROM (VALUES
{rows}
) AS v(zone_id, object_id, kw, txt)
WHERE d.object_zone_id = v.zone_id AND d.object_id = v.object_id
  AND d.keywords = v.kw
  AND position(E'\\n' in d.description) = 0
  AND {old} = {new};
"""


def build(lib: Path) -> str:
    examine_rows, extra_rows, failed = collect(lib)
    out = [HEADER.format(n_examine=len(examine_rows), n_extra=len(extra_rows))]
    if examine_rows:
        rows = ",\n".join(
            f"  ({z}, {i}, {lit(t)}, {lit(p)})" for z, i, t, p in examine_rows
        )
        out.append(
            EXAMINE_SQL.format(
                rows=rows,
                old=COLLAPSE.format(col="o.examine_description"),
                new=COLLAPSE.format(col="v.txt"),
            )
        )
    if extra_rows:
        rows = ",\n".join(
            "  ({}, {}, ARRAY[{}]::text[], {})".format(
                z, i, ", ".join("'" + k.replace("'", "''") + "'" for k in kws), lit(t)
            )
            for z, i, kws, t in extra_rows
        )
        out.append(
            EXTRA_SQL.format(
                rows=rows,
                old=COLLAPSE.format(col="d.description"),
                new=COLLAPSE.format(col="v.txt"),
            )
        )
    out.append("\nCOMMIT;\n")
    for name, err in failed:
        print(f"skipped {name}: {err}", file=sys.stderr)
    return "".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lib", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    sql = build(args.lib)
    args.out.write_text(sql, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
