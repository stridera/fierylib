#!/usr/bin/env python3
"""Generate data/sql/2026-10-11-container-key-composite.sql.

CONTAINER "Key" used to be stored as the legacy vnum (2302). It is now a composite
{"zone": z, "id": i} (object_importer.composite_container_key). This rewrites the positive legacy
numbers that are still in "Objects".values and in the per-instance copies in
"CharacterItems".custom_values, resolving each vnum through the zone ranges in lib/world/zon.

The distinct legacy keys are read from the database named by $PGDATABASE/psql defaults
(`-d fierydev` here); the output only contains the vnum -> (zone, id) pairs, so it is applied
by value and does not depend on row ids.

Usage: python scripts/gen_container_key_sql.py [--lib ../lib] [--db fierydev] [--out PATH]
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from fierylib.converters.dg_to_lua import build_zone_ranges  # noqa: E402
from fierylib.importers.object_importer import composite_container_key  # noqa: E402

QUERY = """
SELECT DISTINCT (values->>'Key')::int FROM "Objects"
 WHERE type = 'CONTAINER' AND jsonb_typeof(values->'Key') = 'number' AND (values->>'Key')::int > 0
UNION
SELECT DISTINCT (custom_values->>'Key')::int FROM "CharacterItems"
 WHERE jsonb_typeof(custom_values->'Key') = 'number' AND (custom_values->>'Key')::int > 0
ORDER BY 1
"""

HEADER = """-- CONTAINER keys as composite ids. "Objects".values->'Key' held the legacy vnum (e.g. 2302 on 23:1);
-- it is now {{"zone": 23, "id": 2}} (fierylib object_importer.composite_container_key, resolved through
-- the zone ranges in lib/world/zon: zone 30 spans 3000-3499, so 3123 is 30:123, not 31:23).
-- Also rewrites the saved per-instance copies in "CharacterItems".custom_values, which the runtime
-- overlays on the prototype. Keys <= 0 ("no key") are left alone.
--
-- Three keys point at objects that do not exist in the legacy data (51 -> 0:51, 1680 -> 16:80,
-- 7911 -> 79:11, no zone range, vnum//100 fallback). They keep the same dangling reference as before.
--
-- Idempotent: only rows whose Key is still a positive JSON number are touched, and each becomes an
-- object, so a second run changes 0 rows.
-- Generated by scripts/gen_container_key_sql.py ({n} legacy keys).

BEGIN;

CREATE TEMP TABLE _container_key_map (legacy integer PRIMARY KEY, zone integer NOT NULL, id integer NOT NULL) ON COMMIT DROP;
INSERT INTO _container_key_map (legacy, zone, id) VALUES
"""

FOOTER = """;

UPDATE "Objects" o
   SET values = jsonb_set(o.values, '{Key}', jsonb_build_object('zone', m.zone, 'id', m.id))
  FROM _container_key_map m
 WHERE o.type = 'CONTAINER'
   AND jsonb_typeof(o.values->'Key') = 'number'
   AND (o.values->>'Key')::int = m.legacy;

UPDATE "CharacterItems" c
   SET custom_values = jsonb_set(c.custom_values, '{Key}', jsonb_build_object('zone', m.zone, 'id', m.id))
  FROM _container_key_map m
 WHERE jsonb_typeof(c.custom_values->'Key') = 'number'
   AND (c.custom_values->>'Key')::int = m.legacy;

COMMIT;
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", default=str(next((p / "lib" for p in ROOT.parents if (p / "lib" / "world" / "zon").is_dir()), ROOT.parent / "lib")))
    ap.add_argument("--db", default="fierydev")
    ap.add_argument("--out", default=str(ROOT / "data" / "sql" / "2026-10-11-container-key-composite.sql"))
    args = ap.parse_args()

    ranges = build_zone_ranges(Path(args.lib) / "world" / "zon")
    if not ranges:
        sys.exit(f"no zone ranges under {args.lib}/world/zon")
    out = subprocess.run(["psql", "-U", "strider", "-d", args.db, "-At", "-c", QUERY],
                         check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.split():
        key = composite_container_key(int(line), ranges)
        rows.append(f"    ({int(line)}, {key['zone']}, {key['id']})")
    sql = HEADER.format(n=len(rows)) + ",\n".join(rows) + FOOTER
    Path(args.out).write_text(sql, encoding="utf-8")
    print(f"wrote {args.out} ({len(rows)} keys)")


if __name__ == "__main__":
    main()
