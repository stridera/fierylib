#!/usr/bin/env python3
"""Generate the room extra-description line-break repair for one or more zones.

fierymud-rs playtest r14 B4: the Academy directory sign (`look sign` in 519:2 and 519:8) printed on one line.

Root cause: World.parse read room extra descriptions with MudData.read_string, which folds every `~`
string onto one line. Object extras were fixed the same way in r10 (MudData.read_text); rooms were
missed. The parser now keeps the layout; this script re-reads lib/world/wld/<zone>.wld with the fixed
parser and emits a guarded, idempotent SQL patch for the RoomExtraDescriptions rows that should have
had line breaks. A row is rewritten only while it still holds the folded single-line text (no line
break, and equal to the new text once whitespace is collapsed), so text edited in Muditor since the
import is left alone, and a rerun matches nothing.

Usage:
    python scripts/gen_room_extra_desc_newlines_sql.py --lib /path/to/lib --zone 519 [--zone N ...] --out PATH
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from mud.mudfile import MudData  # noqa: E402
from mud.types.world import World  # noqa: E402

from fierylib.converters import convert_legacy_colors  # noqa: E402

TAG = "$d$"
COLLAPSE = "btrim(regexp_replace({col}, '\\s+', ' ', 'g'))"


def lit(text: str) -> str:
    assert TAG not in text, "text contains the dollar-quote tag"
    return f"{TAG}{text}{TAG}"


def collect(lib: Path, zones: list[int]):
    rows = []
    for zone in zones:
        f = lib / "world" / "wld" / f"{zone}.wld"
        for room in World.parse(MudData(f.read_text(encoding="latin-1").split("\n"))):
            room_id = int(room["id"]) - zone * 100
            for extra in room.get("extras") or []:
                if "\n" in extra.text:
                    kws = [k for k in extra.keywords if k]
                    rows.append((zone, room_id, kws, convert_legacy_colors(extra.text)))
    return rows


HEADER = """-- fierymud-rs playtest r14 B4: room extra descriptions lost their line breaks on import.
--
-- World.parse folded every `~` string onto one line, so the Academy directory sign (519:2, 519:8)
-- and the other multi-line extra descriptions of the zones below were imported as one long line.
-- The parser now keeps the layout (MudData.read_text); this patch repairs rows imported before that.
--
-- Zones: {zones}. {n} extra descriptions.
--
-- Guarded: a row is rewritten only while it holds the folded text (no line break, equal to the new
-- text once whitespace is collapsed), so anything edited in Muditor since is left alone. Idempotent:
-- after a run the row holds the new text, so a rerun matches nothing.
-- Generated by scripts/gen_room_extra_desc_newlines_sql.py from lib/world/wld/*.wld.

BEGIN;

UPDATE "RoomExtraDescriptions" AS d
SET description = v.txt
FROM (VALUES
{rows}
) AS v(zone_id, room_id, kw, txt)
WHERE d.room_zone_id = v.zone_id AND d.room_id = v.room_id
  AND d.keywords = v.kw
  AND position(E'\\n' in d.description) = 0
  AND {old} = {new};

COMMIT;
"""


def build(lib: Path, zones: list[int]) -> str:
    rows = collect(lib, zones)
    body = ",\n".join(
        "  ({}, {}, ARRAY[{}]::text[], {})".format(
            z, i, ", ".join("'" + k.replace("'", "''") + "'" for k in kws), lit(t)
        )
        for z, i, kws, t in rows
    )
    return HEADER.format(
        zones=", ".join(map(str, zones)),
        n=len(rows),
        rows=body,
        old=COLLAPSE.format(col="d.description"),
        new=COLLAPSE.format(col="v.txt"),
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lib", type=Path, required=True)
    ap.add_argument("--zone", type=int, action="append", required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.write_text(build(args.lib, args.zone), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
